def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv and not argv[0].startswith("-"):
        # `t commit "msg"` means `track commit "msg"`; subcommand names still win.
        if argv[0] in VALID_TYPES:
            argv.insert(0, "track")
        elif argv[0] not in SUBCOMMANDS:
            die(
                "unknown command or type %s; commands: %s; types: %s"
                % (argv[0], ", ".join(SUBCOMMANDS), ", ".join(VALID_TYPES))
            )
    parser = build_parser()
    args = parser.parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()
