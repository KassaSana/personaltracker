    if args.csv:
        events, _unparseable = load_events(vault)
        emit_csv(events)
        return

    weeks = args.weeks if args.weeks is not None else 8
    if args.weeks is not None:
        report_start = week_start(today) - timedelta(weeks=weeks - 1)
    else:
        report_start = today - timedelta(days=int(args.days) - 1)

    all_events, unparseable = load_events(vault, warn_start=report_start)

    if args.pipeline:
        report = pipeline_report(all_events)
        if report is None:
            print("no events with a stage:: field")
            return
        print_lines(render_table(report[0], report[1]))
        return

    week_window = week_start(today) - timedelta(weeks=weeks - 1)
    buckets = weekly_buckets(
        [f for f in all_events if f["_date"] >= week_window], weeks, today
    )

    if args.weeks is not None:
        headers, rows = weekly_report(buckets)
        print_lines(render_table(headers, rows))
        diff = difficulty_report(buckets)
        if diff:
            print("")
            print("leetcode by difficulty")
            print_lines(render_table(diff[0], diff[1]))
    else:
        n = int(args.days)
        window = [f for f in all_events if report_start <= f["_date"] <= today]
        type_counts, study_minutes, missing_duration = summarize(window)

        print("events (%s days)" % n)
        if type_counts:
            for name, count in type_counts.most_common():
                print("  %s  %s" % (name, count))
        else:
            print("  (none)")

        print("study minutes")
        if study_minutes:
            for name, mins in study_minutes.most_common():
                print("  %s  %s" % (name, mins))
        else:
            print("  (none)")
        if missing_duration:
            print("  sessions without duration: %s" % missing_duration)

        days = len(logged_days(window))
        print("logging: %s of %s days had an event" % (days, n))

    print("streaks")
    print_lines(streak_lines(all_events, today))

    if unparseable:
        print("skipped %s unparseable lines" % unparseable, file=sys.stderr)


