def harden_output_encoding(streams):
    """Never die while printing someone else's text.

    Generated text is kept ASCII on purpose, but commit subjects and page titles are
    not ours: an em-dash reaching a cp1252 console raises UnicodeEncodeError and takes
    the command down. Degrade the character, not the run.
    """
    for stream in streams:
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is None:
            continue
        try:
            reconfigure(errors="replace")
        except (ValueError, OSError):
            pass


def main(argv=None):
    harden_output_encoding((sys.stdout, sys.stderr))
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv:
        # A bare `t` should teach, not scold: argparse's "required" usage blob helps
        # nobody, and "what did I log today" is the thing you actually wanted.
        cmd_overview()
        return
    if not argv[0].startswith("-"):
        # `t commit "msg"` means `track commit "msg"`; subcommand names still win.
        if argv[0] == TIME_TYPE:
            # Measured attention cannot be typed: a hand-written hour is a guess.
            die("time events are written by `t watch`, never by hand.")
        if argv[0] in VALID_TYPES:
            argv.insert(0, "track")
        elif argv[0] not in SUBCOMMANDS:
            die(
                "unknown command or type %s.%s\ncommands: %s\ntypes: %s"
                % (
                    argv[0],
                    suggest(argv[0], SUBCOMMANDS + VALID_TYPES),
                    ", ".join(SUBCOMMANDS),
                    ", ".join(VALID_TYPES),
                )
            )
    parser = build_parser()
    if argv[0] == "track":
        # argparse stops collecting `nargs="*"` after an option; keep plain words.
        args, trailing = parser.parse_known_args(argv)
        if any(word.startswith("-") for word in trailing):
            parser.error("unrecognized arguments: %s" % " ".join(trailing))
        args.detail.extend(trailing)
    else:
        args = parser.parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()
