def cmd_stats(args):
    if args.days not in ("7", "30"):
        die("days must be 7 or 30")
    if args.weeks is not None and args.weeks < 1:
        die("--weeks must be at least 1")

    vault = vault_path()
    today = working_date()

    if args.csv:
        events, _unparseable = load_events(vault)
        emit_csv(events)
        return

    weeks = args.weeks if args.weeks is not None else 8
    if args.weeks is not None:
        report_start = week_start(today) - timedelta(weeks=weeks - 1)
    else:
        report_start = today - timedelta(days=int(args.days) - 1)

    all_events, unparseable = load_events(vault, warn_start=report_start)

    if args.pipeline:
        report = pipeline_report(all_events)
        if report is None:
            print("no events with a stage:: field")
            return
        print_lines(render_table(report[0], report[1]))
        return

    week_window = week_start(today) - timedelta(weeks=weeks - 1)
    buckets = weekly_buckets(
        [f for f in all_events if f["_date"] >= week_window], weeks, today
    )

    if args.weeks is not None:
        headers, rows = weekly_report(buckets)
        # Same bars as Dashboard.md: one set of numbers should look like itself
        # wherever you read it.
        print_lines(render_table(*bar_column(headers, rows, 2)))
        diff = difficulty_report(buckets)
        if diff:
            print("")
            print("leetcode by difficulty")
            print_lines(render_table(diff[0], diff[1]))
        times = sibling_module("watch").time_weekly_report(
            [f for f in all_events if f["_date"] >= week_window], weeks, today
        )
        if times:
            print("")
            print("time by category")
            print_lines(render_table(*times))
    else:
        n = int(args.days)
        window = [f for f in all_events if report_start <= f["_date"] <= today]
        type_counts, _study_minutes, missing_duration = summarize(window)

        print("events (%s days)" % n)
        counts = type_count_report(type_counts)
        if counts:
            print_lines("  " + line for line in render_table(*counts))
        else:
            print("  (none)")

        print("study minutes")
        topics = study_topic_report(window)
        if topics:
            print_lines("  " + line for line in render_table(*topics))
        else:
            print("  (none)")
        if missing_duration:
            print("  sessions without duration: %s" % missing_duration)

        times = sibling_module("watch").time_report(window)
        if times:
            print("time by category")
            print_lines("  " + line for line in render_table(*times))

        days = len(logged_days(window))
        print("logging: %s of %s days had an event" % (days, n))

    print("")
    print("streaks")
    print_lines(streak_lines(all_events, today))

    if unparseable:
        print("skipped %s unparseable lines" % unparseable, file=sys.stderr)


