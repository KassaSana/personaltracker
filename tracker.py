# ---- log-line format -------------------------------------------------------


def parse_extra(raw):
    """Parse one --x key=value into a sanitized (key, value) pair."""
    key, sep, value = raw.partition("=")
    key = key.strip()
    value = sanitize(value)
    if not sep or not key:
        die("--x expects key=value, got %s" % raw)
    if not EXTRA_KEY_RE.match(key):
        die("--x key must be letters, digits or underscore, got %s" % key)
    if key in RESERVED_FIELDS:
        die("--x key %s is reserved; use the dedicated flag" % key)
    if not value:
        die("--x value for %s is empty" % key)
    return key, value


def parse_extras(raw_list):
    extras = []
    seen = set()
    for raw in raw_list or ():
        key, value = parse_extra(raw)
        if key in seen:
            die("--x key %s given twice" % key)
        seen.add(key)
        extras.append((key, value))
    return extras


def format_log_line(event_type, when, detail, topic, duration, extras=None):
    parts = [
        "type:: %s" % event_type,
        "when:: %s" % when.strftime("%Y-%m-%dT%H:%M"),
    ]
    if detail:
        parts.append("detail:: %s" % detail)
    if topic:
        parts.append("topic:: %s" % sanitize(topic))
    if duration is not None:
        parts.append("duration:: %s" % duration)
    for key, value in extras or ():
        parts.append("%s:: %s" % (key, value))
    return "- [x] " + " | ".join(parts)


# ---- daily-note I/O --------------------------------------------------------


def end_of_last_nonempty_line(content, start, end):
    insert_at = start
    pos = start
    while pos < end:
        nl_pos = content.find("\n", pos, end)
        if nl_pos == -1:
            line = content[pos:end].rstrip("\r")
            if line.strip():
                insert_at = end
            break
        line = content[pos:nl_pos].rstrip("\r")
        if line.strip():
            insert_at = nl_pos + 1
        pos = nl_pos + 1
    return insert_at


def insert_under_log(content, log_line):
    """Insert log_line under ## Log. Bytes before and after the insert point stay identical."""
    nl = newline_of(content) if content else "\n"
    addition = log_line + nl

    m = LOG_HEADING_RE.search(content)
    if not m:
        # Spec: append \n## Log\n at end, then the line.
        return content + "\n## Log\n" + log_line + "\n"

    after = m.end()
    if after < len(content) and content[after] == "\n":
        after += 1

    next_h2 = NEXT_H2_RE.search(content, after)
    body_end = next_h2.start() if next_h2 else len(content)
    insert_at = end_of_last_nonempty_line(content, after, body_end)

    if insert_at > 0 and content[insert_at - 1] != "\n":
        addition = nl + addition
    return content[:insert_at] + addition + content[insert_at:]


def daily_path(vault, day):
    return os.path.join(vault, "daily", "%s.md" % day.isoformat())


def new_daily_content(vault, day):
    """Seed text for a daily note that does not exist yet.

    A vault template wins if there is one, so a note created by the CLI looks like
    one created by Obsidian. `{{date}}` is Obsidian's own placeholder, so the same
    file serves both. An unreadable template is a warning, never a lost event.
    """
    path = os.path.join(vault, DAILY_TEMPLATE)
    if os.path.isfile(path):
        try:
            body = read_text(path).replace("{{date}}", day.isoformat())
        except OSError:
            print("warning: could not read %s" % path, file=sys.stderr)
        else:
            if body and not body.endswith("\n"):
                body += newline_of(body)
            return body
    return "# %s\n\n## Log\n" % day.isoformat()


# ---- track / today / undo --------------------------------------------------


def cmd_track(args):
    event_type = args.event_type
    if event_type not in VALID_TYPES:
        die(
            "unknown type %s.%s\nexpected one of: %s"
            % (event_type, suggest(event_type, VALID_TYPES), ", ".join(VALID_TYPES))
        )
    if (args.topic is not None or args.duration is not None) and event_type != "study":
        die("--topic and --duration are only valid with type study")

    extras = parse_extras(args.extra)
    vault = vault_path()
    when = now_local()
    if args.date:
        day = parse_iso_date(args.date)
    else:
        day = working_date(when)

    detail = sanitize(" ".join(args.detail)) if args.detail else ""
    log_line = format_log_line(event_type, when, detail, args.topic, args.duration, extras)

    path = daily_path(vault, day)

    os.makedirs(os.path.dirname(path), exist_ok=True)
    with locked_note(path):
        content = read_text(path) if os.path.exists(path) else new_daily_content(vault, day)
        write_text(path, insert_under_log(content, log_line))


def cmd_today(args):
    """What is logged today. Events only: a note seeded from the template is mostly
    unticked boxes and comments, and none of that is something you did."""
    vault = vault_path()
    day = parse_iso_date(args.date) if args.date else working_date()
    path = daily_path(vault, day)
    print(day.isoformat())
    if not os.path.isfile(path):
        print("  (no note)")
        return

    events, waiting = [], 0
    for raw in log_section(read_text(path)).splitlines():
        line = raw.rstrip("\r").strip()
        if COMPLETED_TASK_RE.match(line):
            events.append(line)
        elif line.startswith("- [ ]"):
            waiting += 1

    if not events:
        print("  (no events)")
    for line in events:
        print("  %s" % line)
    if waiting:
        print("  (%d unticked box%s waiting)" % (waiting, "" if waiting == 1 else "es"))


def iter_line_spans(content, start, end):
    """Yield (line_start, line_end) offsets, line_end excluding the newline."""
    pos = start
    while pos < end:
        nl_pos = content.find("\n", pos, end)
        if nl_pos == -1:
            yield pos, end
            return
        yield pos, nl_pos
        pos = nl_pos + 1


def last_tool_line(content):
    """Return (line_start, cut_end, text) of the last tool-written log line, or None."""
    span = log_span(content)
    if span is None:
        return None
    found = None
    for line_start, line_end in iter_line_spans(content, span[0], span[1]):
        text = content[line_start:line_end].rstrip("\r")
        if TOOL_LINE_RE.match(text):
            cut_end = line_end + 1 if line_end < len(content) and content[line_end] == "\n" else line_end
            found = (line_start, cut_end, text)
    return found


def cmd_undo(args):
    vault = vault_path()
    day = parse_iso_date(args.date) if args.date else working_date()
    path = daily_path(vault, day)
    if not os.path.isfile(path):
        die("no daily note for %s" % day.isoformat())

    content = read_text(path)
    found = last_tool_line(content)
    if found is None:
        die("no tracker-written line to undo in %s" % day.isoformat())
    line_start, cut_end, text = found

    print("remove from %s:" % day.isoformat())
    print("  %s" % text)
    if not args.yes:
        if not sys.stdin.isatty():
            print("not a terminal; pass --yes to remove", file=sys.stderr)
            return
        try:
            reply = input("Remove? [y/N] ")
        except EOFError:
            return
        if reply.strip() != "y":
            return

    with locked_note(path):
        latest = read_text(path)
        latest_found = last_tool_line(latest)
        if latest_found is None or latest_found[2] != text:
            die("daily note changed while undo was waiting; run undo again")
        latest_start, latest_end, _latest_text = latest_found
        write_text(path, latest[:latest_start] + latest[latest_end:])


# ---- event loading & parsing -----------------------------------------------
#
# Tolerant reader: anything that does not look like a tracker line is skipped, never
# fatal. The filename is authoritative for which day an event counts under.


def log_span(content):
    """Return (start, end) offsets of the body under ## Log, or None."""
    m = LOG_HEADING_RE.search(content)
    if not m:
        return None
    after = m.end()
    if after < len(content) and content[after] == "\n":
        after += 1
    next_h2 = NEXT_H2_RE.search(content, after)
    end = next_h2.start() if next_h2 else len(content)
    return after, end


def log_section(content):
    span = log_span(content)
    if span is None:
        return ""
    return content[span[0]:span[1]]


def parse_fields(rest):
    fields = {}
    for key, val in FIELD_RE.findall(rest):
        fields[key] = val.strip()
    return fields


def parse_when_field(value):
    try:
        return datetime.fromisoformat(value)
    except ValueError:
        return None


def parse_log_file(path, file_date):
    """Return (events, unparseable_count, mismatch_warnings). Counts go under file_date."""
    content = read_text(path)
    events = []
    unparseable = 0
    warnings = []
    for raw in log_section(content).splitlines():
        line = raw.rstrip("\r")
        m = COMPLETED_TASK_RE.match(line)
        if not m:
            continue
        fields = parse_fields(m.group(1))
        event_type = fields.get("type")
        if not event_type:
            unparseable += 1
            continue
        when_raw = fields.get("when")
        if when_raw:
            when_dt = parse_when_field(when_raw)
            if when_dt is not None:
                delta = abs((when_dt.date() - file_date).days)
                if delta > 1:
                    warnings.append(
                        "warning: %s: when:: %s differs from filename by more than one day"
                        % (os.path.basename(path), when_raw)
                    )
        events.append(fields)
    return events, unparseable, warnings


def iter_day_files(vault):
    """Yield (date, path) for every daily note, oldest first."""
    daily_dir = os.path.join(vault, "daily")
    if not os.path.isdir(daily_dir):
        return
    for name in sorted(os.listdir(daily_dir)):
        m = DAILY_NAME_RE.match(name)
        if not m:
            continue
        try:
            day = datetime.strptime(m.group(1), "%Y-%m-%d").date()
        except ValueError:
            continue
        yield day, os.path.join(daily_dir, name)


def load_events(vault, start=None, end=None, warn_start=None):
    """Return (events, unparseable) for daily notes in [start, end]. Filename is authoritative.

    Streaks need all of history, but complaining about notes outside the window the user
    asked to see is noise: warnings and the unparseable count cover days >= warn_start only.
    """
    events = []
    unparseable = 0
    for day, path in iter_day_files(vault):
        if start is not None and day < start:
            continue
        if end is not None and day > end:
            continue
        try:
            parsed, skipped, warnings = parse_log_file(path, day)
        except OSError:
            # A note we cannot read is a warning, never a crash of the read path.
            print("warning: could not read %s" % path, file=sys.stderr)
            continue
        if warn_start is not None and day >= warn_start:
            unparseable += skipped
            for msg in warnings:
                print(msg, file=sys.stderr)
        for fields in parsed:
            fields["_date"] = day
            events.append(fields)
    return events, unparseable


# ---- numbers engine --------------------------------------------------------


def event_minutes(fields):
    """Study duration in minutes, or None when absent/malformed."""
    try:
        return int((fields.get("duration") or "").strip())
    except ValueError:
        return None


def summarize(events):
    """Counts by type, study minutes by topic, and sessions missing a duration."""
    type_counts = Counter()
    study_minutes = Counter()
    sessions_without_duration = 0
    for fields in events:
        if fields["type"] == TIME_TYPE:
            continue
        type_counts[fields["type"]] += 1
        if fields["type"] != "study":
            continue
        minutes = event_minutes(fields)
        if minutes is None:
            sessions_without_duration += 1
            continue
        study_minutes[fields.get("topic") or "(untagged)"] += minutes
    return type_counts, study_minutes, sessions_without_duration


def logged_days(events):
    return {f["_date"] for f in events if f["type"] != TIME_TYPE}


def streak(days, today, upto=None):
    """(current, longest) run of consecutive days present in `days`."""
    if not days:
        return 0, 0
    ordered = sorted(days)
    longest = 1
    run = 1
    for prev, cur in zip(ordered, ordered[1:]):
        run = run + 1 if (cur - prev).days == 1 else 1
        longest = max(longest, run)

    # Today still counts as unbroken until it is over, so anchor on yesterday
    # when nothing is logged yet today.
    anchor = today if today in days else today - timedelta(days=1)
    current = 0
    while anchor in days:
        current += 1
        anchor -= timedelta(days=1)
    if upto is not None:
        current = min(current, upto)
    return current, longest


# ---- reports & tables ------------------------------------------------------


def render_table(headers, rows):
    widths = [len(h) for h in headers]
    for row in rows:
        for i, cell in enumerate(row):
            widths[i] = max(widths[i], len(cell))
    lines = ["  ".join(h.ljust(widths[i]) for i, h in enumerate(headers)).rstrip()]
    for row in rows:
        lines.append("  ".join(cell.ljust(widths[i]) for i, cell in enumerate(row)).rstrip())
    return lines


def weekly_buckets(events, weeks, today):
    """Newest-first list of per-week aggregates."""
    current_week = week_start(today)
    starts = [current_week - timedelta(weeks=i) for i in range(weeks)]
    by_week = defaultdict(list)
    for fields in events:
        if fields["type"] == TIME_TYPE:
            continue
        by_week[week_start(fields["_date"])].append(fields)

    buckets = []
    for start in starts:
        bucket_events = by_week.get(start, [])
        counts, minutes, _missing = summarize(bucket_events)
        buckets.append(
            {
                "start": start,
                "events": bucket_events,
                "counts": counts,
                "total": len(bucket_events),
                "study_min": sum(minutes.values()),
                "days": len(logged_days(bucket_events)),
            }
        )
    return buckets


def trend_label(buckets, index):
    """Compare a week against the average of the four weeks before it."""
    bucket = buckets[index]
    if bucket["days"] < MIN_LOGGED_DAYS:
        return "low data"
    prior = [b for b in buckets[index + 1: index + 5] if b["days"] >= MIN_LOGGED_DAYS]
    if len(prior) < 2:
        return "n/a"
    avg = sum(b["total"] for b in prior) / len(prior)
    if avg == 0:
        return "n/a"
    pct = (bucket["total"] - avg) / avg * 100
    if abs(pct) < 5:
        return "flat"
    return "%+d%% vs 4wk" % round(pct)


def weekly_report(buckets):
    """Lines for the weekly table: one column per type seen, plus study minutes."""
    totals = Counter()
    for bucket in buckets:
        totals.update(bucket["counts"])
    types = [name for name, _ in totals.most_common()]

    headers = ["week", "days", "events"] + types + ["study_min", "trend"]
    rows = []
    for i, bucket in enumerate(buckets):
        row = [
            bucket["start"].isoformat(),
            str(bucket["days"]),
            str(bucket["total"]),
        ]
        row += [str(bucket["counts"].get(name, 0)) for name in types]
        row.append(str(bucket["study_min"]))
        row.append(trend_label(buckets, i))
        rows.append(row)
    return headers, rows


def difficulty_report(buckets):
    """Weekly leetcode counts by diff::, to catch an easy-only grind."""
    levels = []
    for bucket in buckets:
        for fields in bucket["events"]:
            if fields["type"] != "leetcode":
                continue
            level = fields.get("diff") or "(none)"
            if level not in levels:
                levels.append(level)
    if not levels:
        return None
    order = [lv for lv in ("easy", "medium", "hard") if lv in levels]
    order += [lv for lv in levels if lv not in order]

    headers = ["week"] + order
    rows = []
    for bucket in buckets:
        counts = Counter(
            (f.get("diff") or "(none)") for f in bucket["events"] if f["type"] == "leetcode"
        )
        rows.append([bucket["start"].isoformat()] + [str(counts.get(lv, 0)) for lv in order])
    return headers, rows


def pipeline_report(events):
    """Stage counts across all history, plus conversion between neighbouring stages."""
    counts = Counter()
    for fields in events:
        stage = fields.get("stage")
        if stage:
            counts[stage] += 1
    if not counts:
        return None
    order = [s for s in PIPELINE_STAGES if s in counts]
    order += sorted(s for s in counts if s not in PIPELINE_STAGES)

    rows = []
    for i, stage in enumerate(order):
        conv = ""
        if i > 0 and stage in PIPELINE_STAGES and order[i - 1] in PIPELINE_STAGES:
            prev = counts[order[i - 1]]
            if prev:
                conv = "%d%%" % round(counts[stage] / prev * 100)
        rows.append([stage, str(counts[stage]), conv])
    return ["stage", "count", "from prev"], rows


def streak_lines(events, today, tracked_types=("leetcode", "study")):
    lines = []
    current, longest = streak(logged_days(events), today)
    lines.append("  any event   current %s, longest %s" % (current, longest))
    for name in tracked_types:
        days = {f["_date"] for f in events if f["type"] == name}
        if not days:
            continue
        current, longest = streak(days, today)
        lines.append("  %-11s current %s, longest %s" % (name, current, longest))
    return lines


def print_lines(lines):
    for line in lines:
        print(line)


