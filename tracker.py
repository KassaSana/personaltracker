# ---- sync ------------------------------------------------------------------
#
# Batch import of commits from local git. Not the write path in spirit: a failure just
# means "run it again later". The dedupe key `id::` lives in the Markdown like everything
# else, so re-running is always safe and there is no state file to drift.


def run_git(repo, argv):
    """Run a git command in repo. Returns stdout, or None on any failure."""
    exe = shutil.which("git")
    if not exe:
        return None
    try:
        proc = subprocess.run(
            [exe, "-C", repo] + argv,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
    except OSError:
        return None
    if proc.returncode != 0:
        return None
    return proc.stdout


def git_author_email(repo):
    """The repo's configured user.email — whose commits count as yours."""
    out = run_git(repo, ["config", "user.email"])
    return out.strip() if out else ""


def parse_git_date(text):
    """`%aI` is strict ISO 8601 with an offset; return it as local wall-clock time."""
    try:
        when = datetime.fromisoformat(text.strip())
    except ValueError:
        return None
    if when.tzinfo is not None:
        when = when.astimezone().replace(tzinfo=None)
    return when


def parse_git_log(text):
    """Parse GIT_LOG_FORMAT records into [{sha, when, subject}].

    Tolerant like every other reader here: a record missing fields or carrying an
    unreadable date is skipped, never fatal.
    """
    commits = []
    for raw in (text or "").splitlines():
        parts = raw.rstrip("\r").split(GIT_FIELD_SEP)
        if len(parts) != 3:
            continue
        sha, when_raw, subject = parts
        when = parse_git_date(when_raw)
        if not sha.strip() or when is None:
            continue
        commits.append({"sha": sha.strip(), "when": when, "subject": sanitize(subject)})
    return commits


def git_commits(repo, since, author):
    """Commits by `author` since `since`, or None if the repo could not be read."""
    argv = [
        "log",
        "--no-merges",
        "--since",
        since.isoformat(),
        "--pretty=format:" + GIT_LOG_FORMAT,
    ]
    if author:
        argv += ["--author", author]
    out = run_git(repo, argv)
    return None if out is None else parse_git_log(out)


def is_git_repo(path):
    return os.path.isdir(os.path.join(path, ".git"))


def discover_repos(root):
    """A --root directory plus its immediate subdirectories, keeping the git ones."""
    found = [root] if is_git_repo(root) else []
    try:
        names = sorted(os.listdir(root))
    except OSError:
        print("warning: cannot read --root %s" % root, file=sys.stderr)
        return found
    for name in names:
        path = os.path.join(root, name)
        if is_git_repo(path):
            found.append(path)
    return found


def resolve_repos(repos, roots):
    """Explicit flags win; TRACKER_REPOS is the zero-typing default."""
    paths = list(repos or ())
    for root in roots or ():
        paths += discover_repos(root)
    if not paths:
        raw = os.environ.get("TRACKER_REPOS", "")
        paths = [p for p in raw.split(os.pathsep) if p.strip()]

    # A repo reachable two ways must still be imported once.
    resolved, seen = [], set()
    for path in paths:
        full = os.path.abspath(os.path.expanduser(path.strip()))
        if full not in seen:
            seen.add(full)
            resolved.append(full)
    return resolved


def existing_ids(content):
    """The id:: values a note already carries — sync's dedupe key."""
    ids = set()
    for raw in log_section(content).splitlines():
        m = COMPLETED_TASK_RE.match(raw.rstrip("\r"))
        if not m:
            continue
        value = parse_fields(m.group(1)).get("id")
        if value:
            ids.add(value)
    return ids


def collect_commit_lines(repos, since, author):
    """Map working date -> [(when, id, log line)] for every commit worth appending."""
    by_day = defaultdict(list)
    scanned = 0
    for repo in repos:
        if not is_git_repo(repo):
            print("warning: not a git repository: %s" % repo, file=sys.stderr)
            continue
        who = author or git_author_email(repo)
        if not who:
            print(
                "warning: %s has no git user.email; pass --author" % repo, file=sys.stderr
            )
            continue
        commits = git_commits(repo, since, who)
        if commits is None:
            print("warning: could not read git log in %s" % repo, file=sys.stderr)
            continue
        scanned += 1
        name = sanitize(os.path.basename(repo)) or "repo"
        for commit in commits:
            short = commit["sha"][:SHORT_SHA_LEN]
            extras = [("repo", name), ("id", short), ("src", "sync")]
            line = format_log_line(
                "commit", commit["when"], commit["subject"], None, None, extras
            )
            by_day[working_date(commit["when"])].append((commit["when"], short, line))
    return by_day, scanned


def append_commit_lines(vault, by_day, dry_run):
    """Append the lines whose id the day's note does not already have. Returns (added, skipped)."""
    added = skipped = 0
    for day in sorted(by_day):
        path = daily_path(vault, day)
        content = read_text(path) if os.path.isfile(path) else None
        seen = existing_ids(content) if content is not None else set()

        fresh = []
        for _when, ident, line in sorted(by_day[day]):
            if ident in seen:
                skipped += 1
                continue
            seen.add(ident)
            fresh.append(line)
        if not fresh:
            continue

        added += len(fresh)
        if dry_run:
            print("%s  +%d" % (day.isoformat(), len(fresh)))
            for line in fresh:
                print("  %s" % line)
            continue

        if content is None:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            content = "# %s\n\n## Log\n" % day.isoformat()
        for line in fresh:
            content = insert_under_log(content, line)
        write_text(path, content)
    return added, skipped


def cmd_sync(args):
    if args.days < 1:
        die("--days must be at least 1")
    if not shutil.which("git"):
        die("git is not installed or not on PATH.")

    vault = vault_path()
    repos = resolve_repos(args.repo, args.root)
    if not repos:
        die("no repositories to sync; pass --repo/--root or set TRACKER_REPOS.")

    since = working_date() - timedelta(days=args.days)
    by_day, scanned = collect_commit_lines(repos, since, args.author)
    if not scanned:
        die("no repository could be read; nothing was written.")

    added, skipped = append_commit_lines(vault, by_day, args.dry_run)
    verb = "would add" if args.dry_run else "added"
    print(
        "%s %d event(s) from %d repo(s); %d already logged" % (verb, added, scanned, skipped)
    )


# ---- review ----------------------------------------------------------------
#
# Numbers only change behavior if you read them on a schedule. Unlike Stats.md and
# Dashboard.md, a review is written once and never regenerated: it holds your handwriting.


def review_week_start(today, week=None):
    """Monday of the week under review — last week by default, since you review on Sunday."""
    if week is not None:
        return week_start(week)
    return week_start(today) - timedelta(weeks=1)


def review_path(vault, start):
    year, week_no, _weekday = start.isocalendar()
    return os.path.join(vault, "reviews", "%04d-W%02d.md" % (year, week_no))


def review_markdown(events, start, today):
    """The week's numbers, pre-filled, followed by the three prompts."""
    end = start + timedelta(days=6)
    history = [f for f in events if f["_date"] <= end]
    window = [f for f in history if f["_date"] >= start - timedelta(weeks=REVIEW_CONTEXT_WEEKS)]
    buckets = weekly_buckets(window, REVIEW_CONTEXT_WEEKS + 1, end)

    year, week_no, _weekday = start.isocalendar()
    lines = [
        "# Review %04d-W%02d" % (year, week_no),
        "",
        # ASCII only: this string is printed to consoles whose codepage is not UTF-8.
        "%s to %s. Numbers generated %s; the prompts below are yours to answer."
        % (start.isoformat(), end.isoformat(), today.isoformat()),
        "",
        "## Numbers",
        "",
    ]
    headers, rows = weekly_report(buckets)
    lines += markdown_table(headers, rows)
    lines += ["", "Logged %d of 7 days." % buckets[0]["days"]]
    if buckets[0]["days"] < MIN_LOGGED_DAYS:
        lines.append(
            "Fewer than %d logged days: read this week as insufficient data, not decline."
            % MIN_LOGGED_DAYS
        )
    lines.append("")

    diff = difficulty_report(buckets)
    if diff:
        lines += ["## Leetcode difficulty mix", ""] + markdown_table(*diff) + [""]

    lines += ["## Streaks", ""]
    lines += ["- " + ln.strip() for ln in streak_lines(history, end)]
    lines.append("")

    pipeline = pipeline_report(history)
    if pipeline:
        lines += ["## Application pipeline", ""] + markdown_table(*pipeline) + [""]

    for prompt in REVIEW_PROMPTS:
        lines += ["## %s" % prompt, "", "- ", ""]
    return "\n".join(lines)


def cmd_review(args):
    vault = vault_path()
    today = working_date()
    start = review_week_start(today, parse_iso_date(args.week) if args.week else None)

    events, _unparseable = load_events(vault)
    body = review_markdown(events, start, today)

    if args.print_only:
        print(body)
        return

    path = review_path(vault, start)
    if os.path.exists(path):
        print("review already exists, leaving it alone: %s" % path)
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    write_text(path, body + "\n")
    print("wrote %s" % path)


# ---- label -----------------------------------------------------------------


def load_topics(vault):
    path = os.path.join(vault, "topics.txt")
    if not os.path.isfile(path):
        die("topics.txt not found in VAULT_PATH; create it with one topic per line.")
    topics = []
    for line in read_text(path).splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        topics.append(line)
    if not topics:
        die("topics.txt has no topics.")
    return topics


def iter_recent_notes(vault, since):
    since_ts = since.timestamp()
    for root, _dirs, files in os.walk(vault):
        for name in files:
            if not name.endswith(".md") or name in GENERATED_NOTES:
                continue
            path = os.path.join(root, name)
            try:
                mtime = os.path.getmtime(path)
            except OSError:
                continue
            if mtime < since_ts:
                continue
            yield path


def note_headings(content):
    if content.startswith("﻿"):
        content = content[1:]
    headings = []
    for raw in content.splitlines():
        line = raw.rstrip("\r")
        if HEADING_LINE_RE.match(line):
            headings.append(line)
    return headings


def build_label_prompt(title, headings, topics):
    # Single line: cmd.exe / claude.cmd drop everything after an embedded newline.
    heading_text = " | ".join(headings) if headings else "(no headings)"
    labels = ", ".join(topics)
    return (
        "Note title: %s. Headings: %s. Allowed labels: %s. "
        "Reply with exactly one label from this list, or the word other, and nothing else."
        % (title, heading_text, labels)
    )


def call_claude(prompt):
    exe = shutil.which("claude")
    if not exe:
        die("claude CLI is not installed or not on PATH.")
    argv = [exe, "-p", prompt]
    run_kw = {"capture_output": True, "text": True}
    # npm's claude.cmd is not a Win32 exe.
    if sys.platform == "win32" and exe.lower().endswith((".cmd", ".bat")):
        run_kw["shell"] = True
        argv = subprocess.list2cmdline(argv)
    try:
        proc = subprocess.run(argv, **run_kw)
    except OSError:
        die("claude CLI is not installed or not on PATH.")
    if proc.returncode != 0:
        err = (proc.stderr or proc.stdout or "claude CLI failed").strip()
        die(err.splitlines()[0] if err else "claude CLI failed.")
    return proc.stdout.strip()


def normalize_label(raw, topics):
    token = ""
    if raw.strip():
        token = raw.strip().splitlines()[0].strip()
    if token in topics or token == "other":
        return token, False
    return "other", True


def insert_topic_field(content, label):
    """Insert topic:: after the first heading (or at the top). Existing lines stay intact."""
    nl = newline_of(content) if content else "\n"
    field = "topic:: %s" % label
    bom = 1 if content.startswith("﻿") else 0
    body = content[bom:]
    m = re.search(r"^#{1,6} .*\r?$", body, re.MULTILINE)
    if not m:
        return content[:bom] + field + nl + content[bom:]
    after = bom + m.end()
    if after < len(content) and content[after] == "\n":
        after += 1
    addition = field + nl
    if after > 0 and content[after - 1] != "\n":
        addition = nl + addition
    return content[:after] + addition + content[after:]


def cmd_label(_args):
    vault = vault_path()
    topics = load_topics(vault)
    candidates = []
    for path in iter_recent_notes(vault, working_day_start()):
        content = read_text(path)
        if "topic::" in content:
            continue
        candidates.append((path, content))

    if not candidates:
        print("No notes to label.")
        return

    proposals = []
    for path, content in candidates:
        title = os.path.splitext(os.path.basename(path))[0]
        headings = note_headings(content)
        raw = call_claude(build_label_prompt(title, headings, topics))
        label, fallback = normalize_label(raw, topics)
        rel = os.path.relpath(path, vault)
        if fallback:
            shown = raw.strip().splitlines()[0].strip() if raw.strip() else ""
            print("warning: unexpected label %r for %s; using other" % (shown, rel), file=sys.stderr)
        proposals.append((path, content, label, rel))

    for _path, _content, label, rel in proposals:
        print("%s  %s" % (rel, label))

    if not sys.stdin.isatty():
        return
    try:
        reply = input("Apply? [y/N] ")
    except EOFError:
        return
    if reply.strip() != "y":
        return

    for path, content, label, _rel in proposals:
        write_text(path, insert_topic_field(content, label))


