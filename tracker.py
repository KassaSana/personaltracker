def stats_markdown():
    return (
        GENERATED_HEADER
        + "\n"
        "# Stats\n"
        "\n"
        "## Event counts (last 30 days)\n"
        "\n"
        "```dataview\n"
        "TABLE length(rows) AS Count\n"
        'FROM "daily"\n'
        "WHERE file.day >= date(today) - dur(29 days)\n"
        "FLATTEN file.tasks AS t\n"
        "WHERE t.completed\n"
        'WHERE t.type != "time"\n'
        "GROUP BY t.type\n"
        "SORT Count DESC\n"
        "```\n"
        "\n"
        "## Study minutes by topic\n"
        "\n"
        "```dataview\n"
        "TABLE sum(rows.t.duration) AS Minutes\n"
        'FROM "daily"\n'
        "WHERE file.day >= date(today) - dur(29 days)\n"
        "FLATTEN file.tasks AS t\n"
        'WHERE t.completed AND t.type = "study"\n'
        "GROUP BY t.topic\n"
        "SORT Minutes DESC\n"
        "```\n"
    )


def bar(value, peak, width=BAR_WIDTH):
    """A proportional ASCII bar. Any non-zero value gets at least one mark, so a
    small week reads as small, never as nothing."""
    if value <= 0 or peak <= 0:
        return ""
    return BAR_CHAR * max(1, int(round(value / peak * width)))


def bar_column(headers, rows, source_index, label="chart"):
    """Append a bar column scaled to the largest value in an existing numeric column."""
    values = []
    for row in rows:
        try:
            values.append(int(row[source_index]))
        except ValueError:
            values.append(0)
    peak = max(values) if values else 0
    return headers + [label], [row + [bar(v, peak)] for row, v in zip(rows, values)]


def type_count_report(type_counts):
    """Event counts per type, largest first, with a bar."""
    if not type_counts:
        return None
    peak = max(type_counts.values())
    rows = [[name, str(n), bar(n, peak)] for name, n in type_counts.most_common()]
    return ["type", "count", "chart"], rows


def study_topic_report(events):
    """Study minutes per topic, largest first, with a bar."""
    _counts, minutes, _missing = summarize(events)
    if not minutes:
        return None
    peak = max(minutes.values())
    rows = [[topic, str(mins), bar(mins, peak)] for topic, mins in minutes.most_common()]
    return ["topic", "minutes", "chart"], rows


def markdown_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    for row in rows:
        out.append("| " + " | ".join(row) + " |")
    return out


def dashboard_markdown(events, buckets, today):
    lines = [GENERATED_HEADER.rstrip("\n"), "", "# Dashboard", "", "Generated %s." % today.isoformat(), ""]

    lines += ["## Weekly", ""]
    headers, rows = weekly_report(buckets)
    # The bar tracks total events (column 2) — the number the trend column judges.
    lines += markdown_table(*bar_column(headers, rows, 2))
    lines.append("")
    lines.append(
        "`days` is days-with-at-least-one-event; a week under %s logged days reads as "
        "insufficient data, not decline." % MIN_LOGGED_DAYS
    )
    lines.append("")

    diff = difficulty_report(buckets)
    if diff:
        lines += ["## Leetcode difficulty mix", ""]
        lines += markdown_table(diff[0], diff[1])
        lines.append("")

    window_start = today - timedelta(days=DASHBOARD_TOPIC_DAYS - 1)
    times = sibling_module("watch").time_report(
        [f for f in events if window_start <= f["_date"] <= today]
    )
    if times:
        lines += ["## Time by category (last %d days)" % DASHBOARD_TOPIC_DAYS, ""]
        lines += markdown_table(*times)
        lines.append("")

    lines += ["## Streaks", ""]
    for line in streak_lines(events, today):
        lines.append("- " + line.strip())
    lines.append("")

    pipeline = pipeline_report(events)
    if pipeline:
        lines += ["## Application pipeline", ""]
        lines += markdown_table(pipeline[0], pipeline[1])
        lines.append("")

    lines += ["## Study minutes by topic (last %d days)" % DASHBOARD_TOPIC_DAYS, ""]
    window_start = today - timedelta(days=DASHBOARD_TOPIC_DAYS - 1)
    topics = study_topic_report(
        [f for f in events if window_start <= f["_date"] <= today]
    )
    if topics:
        lines += markdown_table(*topics)
        lines.append("")
    lines += [
        "```dataview",
        "TABLE sum(rows.t.duration) AS Minutes",
        'FROM "daily"',
        "WHERE file.day >= date(today) - dur(29 days)",
        "FLATTEN file.tasks AS t",
        'WHERE t.completed AND t.type = "study"',
        "GROUP BY t.topic",
        "SORT Minutes DESC",
        "```",
        "",
    ]
    return "\n".join(lines)


def emit_csv(events):
    base = ["date", "type", "when", "detail", "topic", "duration"]
    extra = sorted({k for f in events for k in f if k not in base and not k.startswith("_")})
    writer = csv.writer(sys.stdout, lineterminator="\n")
    writer.writerow(base + extra)
    for fields in events:
        row = [fields["_date"].isoformat()]
        row += [fields.get(name, "") for name in base[1:]]
        row += [fields.get(name, "") for name in extra]
        writer.writerow(row)


