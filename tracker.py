# folded into `stats`: "show me numbers" must never rewrite notes as a side effect.


def write_generated_notes(vault, weeks=DASH_WEEKS):
    """Overwrite Stats.md and Dashboard.md. The only writes outside daily notes."""
    today = working_date()
    events, _unparseable = load_events(vault)
    window = week_start(today) - timedelta(weeks=weeks - 1)
    buckets = weekly_buckets([f for f in events if f["_date"] >= window], weeks, today)

    for name, body in (
        ("Stats.md", stats_markdown()),
        ("Dashboard.md", dashboard_markdown(events, buckets, today)),
    ):
        path = os.path.join(vault, name)
        write_text(path, body)
        print("wrote %s" % path)


def cmd_dash(args):
    if args.weeks < 1:
        die("--weeks must be at least 1")
    write_generated_notes(vault_path(), args.weeks)


def existing_ids(content):
    """Return durable dedupe IDs from completed tasks in the Log section."""
    ids = set()
    for raw in log_section(content).splitlines():
        m = COMPLETED_TASK_RE.match(raw.rstrip("\r"))
        if not m:
            continue
        value = parse_fields(m.group(1)).get("id")
        if value:
            ids.add(value)
    return ids


def append_commit_lines(vault, by_day, dry_run):
    """Append the lines whose id the day's note does not already have. Returns (added, skipped)."""
    added = skipped = 0
    for day in sorted(by_day):
        path = daily_path(vault, day)
        with locked_note(path):
            content = read_text(path) if os.path.isfile(path) else None
            seen = existing_ids(content) if content is not None else set()
            fresh = []
            for _when, ident, line in sorted(by_day[day]):
                if ident in seen:
                    skipped += 1
                    continue
                seen.add(ident)
                fresh.append(line)
            if not fresh:
                continue
            added += len(fresh)
            if dry_run:
                print("%s  +%d" % (day.isoformat(), len(fresh)))
                for line in fresh:
                    print("  %s" % line)
                continue
            os.makedirs(os.path.dirname(path), exist_ok=True)
            content = content if content is not None else new_daily_content(vault, day)
            for line in fresh:
                content = insert_under_log(content, line)
            write_text(path, content)
    return added, skipped


